import config
import unlocks
import farm
import maze
import pumpkin
import cactus
import dinosaur
import workers
import utils


# ==================================================
# RESTORE NORMAL FARM
# ==================================================

def restore_normal_farm():
    clear()

    workers.set_main_hat()

    farm.rebuild_sunflowers()


# ==================================================
# PRODUCER INPUTS
# ==================================================

def producer_multiplier(item):
    world_size = utils.size()

    if item == Items.Pumpkin:
        return (
            world_size
            * world_size
            * config.PUMPKIN_COST_FACTOR
        )

    if item == Items.Cactus:
        return (
            world_size
            * world_size
        )

    # Normal crops only need enough input to start making progress.
    # The next planner iteration will re-evaluate inventory/costs.
    return 1


def producer_prerequisite(item):
    producer = unlocks.producer_for(item)

    if producer == None:
        return None

    cost = get_cost(producer)

    return unlocks.choose_focus_from_cost(
        cost,
        producer_multiplier(item)
    )


# ==================================================
# BASIC RESOURCES
# ==================================================

def run_basic(item):
    prerequisite = producer_prerequisite(item)

    if (
        prerequisite != None
        and prerequisite != item
    ):
        return run(prerequisite)

    farm.run(item)

    return True


# ==================================================
# PUMPKIN
# ==================================================

def run_pumpkin():
    if pumpkin.can_start():
        success = pumpkin.run()

        restore_normal_farm()

        return success

    prerequisite = producer_prerequisite(
        Items.Pumpkin
    )

    if prerequisite != None:
        return run(prerequisite)

    # Conservative fallback: pumpkin planting normally depends on
    # carrots, and the planner will re-evaluate after this farm run.
    farm.run(Items.Carrot)

    return True


# ==================================================
# CACTUS
# ==================================================

def run_cactus():
    if cactus.can_start():
        success = cactus.run()

        restore_normal_farm()

        return success

    prerequisite = producer_prerequisite(
        Items.Cactus
    )

    if prerequisite != None:
        return run(prerequisite)

    farm.run(Items.Pumpkin)

    return True


# ==================================================
# BONES / DINOSAUR
# ==================================================

def run_bones():
    if dinosaur.can_start():
        success = dinosaur.run()

        restore_normal_farm()

        return success

    # Apples consume Cactus. If we cannot start the Dinosaur job,
    # Cactus is therefore the first resource to replenish.
    return run(Items.Cactus)


# ==================================================
# GOLD / MAZE
# ==================================================

def run_gold():
    if maze.can_start():
        success = maze.run()

        restore_normal_farm()

        return success

    # First ensure the Bush itself is affordable.
    bush_focus = unlocks.choose_focus_from_cost(
        get_cost(Entities.Bush)
    )

    if bush_focus != None:
        return run(bush_focus)

    # Gold requires a Maze, and a Maze requires Weird Substance.
    # Weird Substance is generated by harvesting fertilized normal
    # crops, so run a normal high-throughput Grass cycle until
    # maze.can_start() becomes true on a later planner iteration.
    farm.run(Items.Hay)

    return True


# ==================================================
# RESOURCE DISPATCH
# ==================================================

def run(item):
    if item == None:
        farm.run()
        return True

    if item == Items.Pumpkin:
        return run_pumpkin()

    if item == Items.Cactus:
        return run_cactus()

    if item == Items.Bone:
        return run_bones()

    if item == Items.Gold:
        return run_gold()

    if (
        item == Items.Power
        or item == Items.Hay
        or item == Items.Wood
        or item == Items.Carrot
    ):
        return run_basic(item)

    # Unknown future resource:
    # keep the farm productive instead of stalling.
    farm.run()

    return False
